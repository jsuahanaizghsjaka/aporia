function q(
  skill: SkillId,
  suffix: string,
  prompt: string,
  answers: string[],
  explanation: string,
  hints: [string, string],
  code?: string,
  choices?: string[],
): Question {
  return {
    id: `${skill}.${suffix}`,
    skill,
    prompt,
    answers,
    explanation,
    hints,
    code,
    choices,
    partial:
      partials[`${skill}.${suffix}`] ??
      `${hints[1]}\nСоставь промежуточный шаг и проверь его на данных из задания.`,
    solution: `Ответ: ${answers[0]}\n${explanation}`,
  };
}
