export function resolveTeacher(
  skill: SkillId,
  raw: unknown,
  source: "ai" | "prepared",
) {
  const choice = teacherChoiceSchema.parse(raw);
  return {
    source,
    choice,
    explanation:
      choice.explanation === "analogy"
        ? analogies[skill]
        : choice.explanation === "mistake"
          ? `Сначала отделим понятие от конкретного ответа. ${concepts[skill]} Проверь, какой шаг было труднее объяснить в прошлый раз.`
          : concepts[skill],
    reflection: reflections[choice.reflection],
  };
}
